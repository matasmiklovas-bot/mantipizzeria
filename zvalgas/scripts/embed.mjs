// Builds the web page from the artifact source: same HTML, plus the window.claude shim and web-only tags.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
let html = readFileSync(join(root, "artifact/index.html"), "utf8");
const shim = readFileSync(join(root, "src/client/shim.js"), "utf8");

const head = `<meta name="theme-color" content="#0d1611">
<meta name="apple-mobile-web-app-capable" content="yes">
<meta name="apple-mobile-web-app-status-bar-style" content="black-translucent">
<meta name="robots" content="noindex">
<link rel="icon" href="/icon.svg" type="image/svg+xml">
<link rel="apple-touch-icon" href="/icon.svg">
<link rel="manifest" href="/manifest.webmanifest">`;
if (!html.includes("<title>Coldai</title>")) throw new Error("title not found");
html = html.replace("<title>Coldai</title>", `<title>Coldai</title>\n${head}`);

const marker = "<script>\n/* ===== constants ===== */";
if (!html.includes(marker)) throw new Error("app script marker not found");
html = html.replace(marker, `<script>\n${shim}\n</script>\n${marker}`);

mkdirSync(join(root, "src/generated"), { recursive: true });
writeFileSync(join(root, "src/generated/app-html.ts"), `// Generated by scripts/embed.mjs from artifact/index.html. Do not edit.\nexport const APP_HTML = ${JSON.stringify(html)};\n`);
console.log(`embed: ${Math.round(html.length / 1024)} KB`);
